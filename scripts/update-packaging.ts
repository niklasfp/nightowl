// Regenerates the Homebrew formula and winget manifests for a release.
//
//   node scripts/update-packaging.ts [--force] <version-without-v> <path-to-SHA256SUMS.txt>
//
// The committed Formula/nightowl.rb and packaging/winget/*.yaml are the verbatim output of
// this script; the `packaging` job in release.yml reruns it on every tag and commits the
// result to main. Zero dependencies — runs on Node >= 22.18 via native TS type-stripping.
//
// Tags are not monotonic (a hotfix like v0.1.1 can be cut after v0.2.0 already shipped), so
// before writing anything this script compares the requested version against the version
// already committed in Formula/nightowl.rb. A strictly older request is a no-op: it prints a
// message and exits 0 without touching any files, so the manifests never regress to an older
// series. Equal or newer requests regenerate as normal (re-running a release stays idempotent).
// Pass --force, or set NIGHTOWL_PACKAGING_FORCE=1, to override the skip for a deliberate
// rollback. --force may appear anywhere among the arguments.
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = join(import.meta.dirname, "..");
const rawArgs = process.argv.slice(2);
const force = rawArgs.includes("--force") || process.env.NIGHTOWL_PACKAGING_FORCE === "1";
const [version, sumsPath] = rawArgs.filter((a) => !a.startsWith("--"));
if (!version || !sumsPath) {
  console.error("usage: node scripts/update-packaging.ts [--force] <version> <SHA256SUMS.txt>");
  process.exit(2);
}
if (version.startsWith("v")) {
  console.error(`version must not include the leading 'v' (got '${version}')`);
  process.exit(2);
}

// Hand-rolled semver-ish compare: split into main + prerelease on the first '-'. Main parts
// split on '.' and compare numerically field-by-field (missing fields are 0). A version WITH a
// prerelease suffix sorts BELOW the same main version without one. Prerelease identifiers split
// on '.' and compare numerically when both sides are numeric, otherwise as strings.
function splitVersion(v: string): { main: string; prerelease: string | null } {
  const i = v.indexOf("-");
  return i === -1 ? { main: v, prerelease: null } : { main: v.slice(0, i), prerelease: v.slice(i + 1) };
}
function compareMain(a: string, b: string): number {
  const pa = a.split(".").map(Number);
  const pb = b.split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const na = pa[i] ?? 0;
    const nb = pb[i] ?? 0;
    if (na !== nb) return na - nb;
  }
  return 0;
}
function comparePrereleaseIdentifier(a: string, b: string): number {
  const na = Number(a);
  const nb = Number(b);
  const aNumeric = a !== "" && !Number.isNaN(na);
  const bNumeric = b !== "" && !Number.isNaN(nb);
  if (aNumeric && bNumeric) return na - nb;
  return a < b ? -1 : a > b ? 1 : 0;
}
function comparePrerelease(a: string | null, b: string | null): number {
  if (a === b) return 0;
  if (a === null) return 1; // no prerelease outranks any prerelease
  if (b === null) return -1;
  const pa = a.split(".");
  const pb = b.split(".");
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    if (pa[i] === undefined) return -1;
    if (pb[i] === undefined) return 1;
    const c = comparePrereleaseIdentifier(pa[i], pb[i]);
    if (c !== 0) return c;
  }
  return 0;
}
function compareVersions(a: string, b: string): number {
  const va = splitVersion(a);
  const vb = splitVersion(b);
  const mainCmp = compareMain(va.main, vb.main);
  return mainCmp !== 0 ? mainCmp : comparePrerelease(va.prerelease, vb.prerelease);
}

function committedVersion(): string {
  try {
    const rb = readFileSync(join(root, "Formula", "nightowl.rb"), "utf8");
    const m = rb.match(/version\s+"([^"]+)"/);
    return m ? m[1] : "0";
  } catch {
    return "0";
  }
}

if (!force) {
  const current = committedVersion();
  if (compareVersions(version, current) < 0) {
    console.log(`manifests stay at ${current}; ${version} is a hotfix for an older series`);
    process.exit(0);
  }
}

const sums = new Map<string, string>();
for (const line of readFileSync(sumsPath, "utf8").split("\n")) {
  const m = line.trim().match(/^([0-9a-fA-F]{64})\s+\*?(.+)$/);
  if (m) sums.set(m[2], m[1].toLowerCase());
}
function sha(asset: string): string {
  const s = sums.get(asset);
  if (!s) {
    console.error(`missing checksum for ${asset} in ${sumsPath}`);
    process.exit(1);
  }
  return s;
}
const url = (asset: string) =>
  `https://github.com/niklasfp/nightowl/releases/download/v${version}/${asset}`;

const formula = `# Generated by scripts/update-packaging.ts — do not edit by hand.
class Nightowl < Formula
  desc "Cross-platform keep-the-computer-awake CLI"
  homepage "https://niklasfp.github.io/nightowl/"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${url("nightowl-osx-arm64.tar.gz")}"
      sha256 "${sha("nightowl-osx-arm64.tar.gz")}"
    end
  end

  on_linux do
    on_intel do
      url "${url("nightowl-linux-x64.tar.gz")}"
      sha256 "${sha("nightowl-linux-x64.tar.gz")}"
    end
    on_arm do
      url "${url("nightowl-linux-arm64.tar.gz")}"
      sha256 "${sha("nightowl-linux-arm64.tar.gz")}"
    end
  end

  def install
    bin.install "nightowl"
  end

  test do
    assert_match(/\\d+\\.\\d+/, shell_output("#{bin}/nightowl --version"))
  end
end
`;

const manifestVersion = "1.6.0";
const id = "niklasfp.NightOwl";

const versionManifest = `# Generated by scripts/update-packaging.ts — do not edit by hand.
PackageIdentifier: ${id}
PackageVersion: ${version}
DefaultLocale: en-US
ManifestType: version
ManifestVersion: ${manifestVersion}
`;

const installerManifest = `# Generated by scripts/update-packaging.ts — do not edit by hand.
PackageIdentifier: ${id}
PackageVersion: ${version}
InstallerType: zip
NestedInstallerType: portable
NestedInstallerFiles:
  - RelativeFilePath: nightowl.exe
    PortableCommandAlias: nightowl
Installers:
  - Architecture: x64
    InstallerUrl: ${url("nightowl-win-x64.zip")}
    InstallerSha256: ${sha("nightowl-win-x64.zip").toUpperCase()}
  - Architecture: arm64
    InstallerUrl: ${url("nightowl-win-arm64.zip")}
    InstallerSha256: ${sha("nightowl-win-arm64.zip").toUpperCase()}
ManifestType: installer
ManifestVersion: ${manifestVersion}
`;

const localeManifest = `# Generated by scripts/update-packaging.ts — do not edit by hand.
PackageIdentifier: ${id}
PackageVersion: ${version}
PackageLocale: en-US
Publisher: Niklas Petersen
PublisherUrl: https://github.com/niklasfp
PublisherSupportUrl: https://github.com/niklasfp/nightowl/issues
PackageName: NightOwl
PackageUrl: https://niklasfp.github.io/nightowl/
License: MIT
LicenseUrl: https://github.com/niklasfp/nightowl/blob/main/LICENSE
ShortDescription: Cross-platform "keep the computer awake" CLI
Moniker: nightowl
Tags:
  - awake
  - caffeinate
  - cli
  - keep-awake
  - sleep-inhibitor
ManifestType: defaultLocale
ManifestVersion: ${manifestVersion}
`;

mkdirSync(join(root, "Formula"), { recursive: true });
writeFileSync(join(root, "Formula", "nightowl.rb"), formula);
const wingetDir = join(root, "packaging", "winget");
mkdirSync(wingetDir, { recursive: true });
writeFileSync(join(wingetDir, `${id}.yaml`), versionManifest);
writeFileSync(join(wingetDir, `${id}.installer.yaml`), installerManifest);
writeFileSync(join(wingetDir, `${id}.locale.en-US.yaml`), localeManifest);
console.log(`Packaging manifests updated for v${version}.`);
